from scapy.all import *
import time

"""
UDP test traffic for the packet sniffer (generated by Scapy)
Note: sent to loopback interface currently, can be changed
"""

# Test Case 1: basic UDP packet
udp_packet = (
    IP(dst="127.0.0.1")
    / UDP(sport=4000, dport=9999)
    / Raw(load=b"AMANDA_AVY_GIO_JACKSON_UDP_TESTING")
)

# Test Case 2: different ports
udp_ports = (
    IP(dst="127.0.0.1")
    / UDP(sport=5000, dport=8888)
    / Raw(load=b"TEST_UDP_PORTS")
)

# Test Case 3: no payload
udp_no_payload = (
    IP(dst="127.0.0.1")
    / UDP(sport=4001, dport=9999)
)

# Test Case 4: DNS port (53)
udp_dns = (
    IP(dst="127.0.0.1")
    / UDP(sport=5353, dport=53)
    / Raw(load=b"TEST_UDP_DNS")
)

# Test Case 6: larger payload
udp_large_payload = (
    IP(dst="127.0.0.1")
    / UDP(sport=4002, dport=9999)
    / Raw(load=b"Y" * 1000)
)

udp_packets = [udp_packet, udp_ports, udp_no_payload, udp_dns, udp_large_payload]

def run():
    # main.py will call this method after the sniffer is started
    for packet in udp_packets:
        send(packet)
        time.sleep(0.5)
    
    print("All UDP Test Packets Sent")

if __name__ == "__main__":
    run()